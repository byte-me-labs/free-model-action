#!/usr/bin/env node
/**
 * Turn one result JSON into GitHub Action outputs, a job summary, and an
 * optional comment body.
 *
 * Outputs are written with a random heredoc delimiter so an answer containing
 * the delimiter cannot truncate the output. Comment text is sanitized before
 * it leaves this process: control characters are stripped and `@` is escaped
 * so a model cannot ping a real account.
 *
 * @module scripts/emit-result.mjs
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

/** A fence longer than the longest backtick run in the text. */
export function fenceFor(value) {
  const runs = String(value ?? '').match(/`+/g) ?? []
  const longest = runs.reduce((max, run) => Math.max(max, run.length), 0)
  return '`'.repeat(Math.max(3, longest + 1))
}

/** Remove control bytes and neutralize mentions in model-authored text. */
export function sanitizeComment(value) {
  return String(value ?? '')
    .replace(/\r\n/g, '\n')
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '')
    .replace(/@/g, '@​')
    .trim()
}

function number(value) {
  return typeof value === 'number' && Number.isFinite(value) ? value : 0
}

/** Markdown for $GITHUB_STEP_SUMMARY. */
export function formatSummary(result, { maxTextChars = 20_000 } = {}) {
  const lines = ['### Free model call', '']
  lines.push(`- ok: \`${result.ok === true}\``)
  if (result.lane) lines.push(`- lane: \`${result.lane}\``)
  if (result.model) lines.push(`- model: \`${result.model}\``)
  if (result.modelSource) lines.push(`- model source: \`${result.modelSource}\``)
  if (result.finish) lines.push(`- finish: \`${result.finish}\``)
  if (typeof result.elapsedMs === 'number') lines.push(`- elapsed: ${result.elapsedMs}ms`)
  if (result.usage && typeof result.usage === 'object') {
    lines.push(`- usage: in ${number(result.usage.inputTokens)} / out ${number(result.usage.outputTokens)} / total ${number(result.usage.totalTokens)}`)
  }
  if (typeof result.redactions === 'number' && result.redactions > 0) {
    lines.push(`- redactions: ${result.redactions}`)
  }
  if (result.inputTruncated === true) {
    lines.push(`- input truncated: ${number(result.inputOmittedChars)} characters omitted`)
  }
  lines.push('')

  if (result.ok === true) {
    const text = String(result.text ?? '')
    const shown = text.length > maxTextChars
      ? `${text.slice(0, maxTextChars)}\n\n[summary truncated]`
      : text
    const fence = fenceFor(shown)
    lines.push(`${fence}text`, shown, fence)
  } else {
    lines.push(`**Failed:** \`${result.code ?? 'UNKNOWN'}\``)
    if (typeof result.message === 'string' && result.message !== '') {
      lines.push('', result.message)
    }
    if (Array.isArray(result.attempts) && result.attempts.length > 0) {
      lines.push('', '| lane | model | result | code | ms |', '| --- | --- | --- | --- | --- |')
      for (const attempt of result.attempts) {
        lines.push(`| ${attempt.lane ?? ''} | ${attempt.model ?? ''} | ${attempt.ok ? 'ok' : 'failed'} | ${attempt.code ?? ''} | ${attempt.elapsedMs ?? ''} |`)
      }
    }
  }
  lines.push('', '<sub>Free model lanes may log prompts upstream. Do not send secrets.</sub>')
  return `${lines.join('\n')}\n`
}

/** GitHub rejects a comment body over 65536 characters. */
export const MAX_COMMENT_CHARS = 60_000

/** A comment body, or '' when the call did not produce an answer. */
export function formatComment(result) {
  if (result.ok !== true) return ''
  let text = sanitizeComment(result.text)
  if (text === '') return ''
  if (text.length > MAX_COMMENT_CHARS) {
    text = `${text.slice(0, MAX_COMMENT_CHARS)}\n\n[comment truncated]`
  }
  const model = result.model ? ` \`${result.model}\`` : ''
  const lane = result.lane ? ` (${result.lane})` : ''
  return [
    '<!-- free-model-action -->',
    `🤖 **Free model result**${lane}${model}`,
    '',
    text,
    '',
    '<sub>Generated by a free model lane. Prompts may be logged upstream; verify before acting.</sub>',
    '',
  ].join('\n')
}

function writeOutputs(result, resultFile) {
  const file = process.env.GITHUB_OUTPUT
  if (!file) return
  const text = String(result.text ?? '')
  let delimiter = `__OFM_EOF_${crypto.randomUUID()}__`
  while (text.includes(delimiter)) delimiter = `__OFM_EOF_${crypto.randomUUID()}__`
  const lines = [
    `ok=${result.ok === true}`,
    `lane=${result.lane ?? ''}`,
    `model=${result.model ?? ''}`,
    `finish=${result.finish ?? ''}`,
    `result-file=${resultFile}`,
    `text<<${delimiter}`,
    text,
    delimiter,
  ]
  fs.appendFileSync(file, `${lines.join('\n')}\n`)
}

function parseArgs(argv) {
  const args = { result: null, summary: false, commentFile: null }
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index]
    if (flag === '--result') args.result = argv[++index]
    else if (flag === '--summary') args.summary = true
    else if (flag === '--comment-file') args.commentFile = argv[++index]
    else throw new Error(`unknown flag ${flag}`)
  }
  if (!args.result) throw new Error('--result is required')
  return args
}

export function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv)
  const resultFile = path.resolve(args.result)
  let result
  try {
    result = JSON.parse(fs.readFileSync(resultFile, 'utf8'))
  } catch (error) {
    result = {
      ok: false,
      code: 'NO_RESULT',
      message: `cannot read ${args.result}: ${error?.message ?? error}`,
      attempts: [],
    }
  }
  if (result === null || typeof result !== 'object' || Array.isArray(result)) {
    result = { ok: false, code: 'BAD_RESULT', message: 'result JSON is not an object', attempts: [] }
  }
  writeOutputs(result, resultFile)
  if (args.summary && typeof process.env.GITHUB_STEP_SUMMARY === 'string' && process.env.GITHUB_STEP_SUMMARY !== '') {
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, formatSummary(result))
  }
  if (args.commentFile) {
    const body = formatComment(result)
    if (body !== '') {
      const commentFile = path.resolve(args.commentFile)
      fs.mkdirSync(path.dirname(commentFile), { recursive: true })
      fs.writeFileSync(commentFile, body)
    }
  }
  return result.ok === true ? 0 : 1
}

const isMain = process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  try {
    process.exitCode = main()
  } catch (error) {
    process.stderr.write(`emit-result: ${error?.stack ?? error}\n`)
    process.exitCode = 2
  }
}
